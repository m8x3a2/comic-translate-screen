// Regenerates lib/src/bindings/ort_bindings.g.dart from the vendored
// onnxruntime_c_api.h. Requires LLVM (libclang): `winget install LLVM.LLVM`.
//
//   dart run tool/ffigen.dart

import 'dart:io';

import 'package:ffigen/ffigen.dart';

const _structs = {'OrtApi', 'OrtApiBase'};
const _funcs = {'OrtGetApiBase'};
const _enums = {
  'ONNXTensorElementDataType',
  'ONNXType',
  'OrtLoggingLevel',
  'OrtErrorCode',
  'GraphOptimizationLevel',
  'ExecutionMode',
  'OrtAllocatorType',
  'OrtMemType',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = root.resolve('third_party/onnxruntime/include/onnxruntime_c_api.h');
  final includeDir = root.resolve('third_party/onnxruntime/include/');
  final generator = FfiGenerator(
    input: Input(entryPoints: [header], include: (h) => h.toString().startsWith(includeDir.toString())),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/bindings/ort_bindings.g.dart')),
      preamble: '''
// Generated by tool/ffigen.dart from onnxruntime_c_api.h (ONNX Runtime,
// Copyright (c) Microsoft Corporation, MIT license). Do not edit.
// ignore_for_file: type=lint, unused_field, unused_element
''',
      style: const NativeExternalBindings(assetId: 'package:ct_onnx/onnxruntime'),
    ),
    visitors: [
      Visitor(
        func: (f) => f.isIncluded = _funcs.contains(f.originalName),
        struct: (s) => s.isIncluded = _structs.contains(s.originalName),
        enumClass: (e) => e.isIncluded = _enums.contains(e.originalName),
        global: (g) => g.isIncluded = false,
        macroConstant: (m) => m.isIncluded = m.originalName == 'ORT_API_VERSION',
        unnamedEnumConstant: (c) => c.isIncluded = false,
      ),
    ],
  );
  final libclang = Platform.isWindows ? Uri.file(r'C:\Program Files\LLVM\bin\libclang.dll') : null;
  await generator.generate(libclangDylib: libclang);
}
