// Regenerates lib/src/bindings/llama_bindings.g.dart from the vendored
// llama.h. Requires LLVM (libclang): `winget install LLVM.LLVM`.
//
//   dart run tool/ffigen.dart
//
// The few functions of mtmd.dll and ggml.dll are written by hand in
// lib/src/bindings/mtmd.dart (another library each).

import 'dart:io';

import 'package:ffigen/ffigen.dart';

const _funcs = {
  'llama_backend_init',
  'llama_log_set',
  'llama_model_default_params',
  'llama_context_default_params',
  'llama_sampler_chain_default_params',
  'llama_model_load_from_file',
  'llama_model_free',
  'llama_init_from_model',
  'llama_free',
  'llama_n_ctx',
  'llama_get_memory',
  'llama_memory_clear',
  'llama_model_get_vocab',
  'llama_vocab_is_eog',
  'llama_vocab_n_tokens',
  'llama_token_to_piece',
  'llama_batch_get_one',
  'llama_decode',
  'llama_sampler_chain_init',
  'llama_sampler_chain_add',
  'llama_sampler_init_greedy',
  'llama_sampler_init_penalties',
  'llama_sampler_sample',
  'llama_sampler_accept',
  'llama_sampler_reset',
  'llama_sampler_free',
};

Future<void> main() async {
  final root = Platform.script.resolve('../');
  final header = root.resolve('third_party/llama.cpp/include/llama.h');
  final includeDir = root.resolve('third_party/llama.cpp/include/');
  final generator = FfiGenerator(
    input: Input(entryPoints: [header], include: (h) => h.toString().startsWith(includeDir.toString())),
    output: Output(
      dart: DartOutput(path: root.resolve('lib/src/bindings/llama_bindings.g.dart')),
      preamble: '''
// Generated by tool/ffigen.dart from llama.h (llama.cpp, Copyright (c) 2023-2026
// The ggml authors, MIT license). Do not edit.
// ignore_for_file: type=lint, unused_field, unused_element
''',
      style: const NativeExternalBindings(assetId: 'package:ct_llama/llama'),
    ),
    visitors: [
      Visitor(
        func: (f) => f.isIncluded = _funcs.contains(f.originalName),
        global: (g) => g.isIncluded = false,
        macroConstant: (m) => m.isIncluded = false,
        unnamedEnumConstant: (c) => c.isIncluded = false,
      ),
    ],
  );
  final libclang = Platform.isWindows ? Uri.file(r'C:\Program Files\LLVM\bin\libclang.dll') : null;
  await generator.generate(libclangDylib: libclang);
}
