"""Generates packages/ct_core/lib/src/ocr/manga_ocr_tables.g.dart from the
original's manga-ocr post-processing (jaconv.h2z tables and the literal
strings of modules/ocr/manga_ocr/mobile/onnx_engine.py).

    uv run python -B gen_manga_ocr_tables.py [--original DIR]
"""

from __future__ import annotations

import argparse
import inspect
import os
import re
from pathlib import Path

import jaconv
from jaconv import conv_table

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "packages" / "ct_core" / "lib" / "src" / "ocr" / "manga_ocr_tables.g.dart"


BS = chr(92)


def dart_str(s: str) -> str:
    return "'" + "".join(BS + f"u{{{ord(c):x}}}" if ord(c) > 126 or c in ("'", BS, "$") else c for c in s) + "'"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--original", type=Path, default=Path(os.environ.get("CT_ORIGINAL_DIR", REPO.parent.parent / "official")))
    args = ap.parse_args()

    # Dakuten replacements, in the order h2z applies them.
    src = inspect.getsource(jaconv.h2z)
    pairs = re.findall(r"replace\('(..)', '(.)'\)", src)
    table = conv_table.H2Z_ALL

    engine = (args.original / "modules" / "ocr" / "manga_ocr" / "mobile" / "onnx_engine.py").read_text(encoding="utf-8")
    mojibake = re.search(r'text\.replace\("([^"]+)", "\.\.\."\)', engine).group(1)
    mojibake_class = re.search(r're\.sub\("\[([^\]]+)\]\{2,\}"', engine).group(1)

    lines = [
        "// GENERATED by tools/reference/gen_manga_ocr_tables.py — do not edit.",
        f"// jaconv {jaconv.__version__}; strings from the original manga-ocr engine.",
        "",
        "part of 'manga_ocr.dart';",
        "",
        "/// `jaconv.h2z` dakuten replacements, in order.",
        "const _h2zDakuten = <(String, String)>[",
        *[f"  ({dart_str(a)}, {dart_str(b)})," for a, b in pairs],
        "];",
        "",
        "/// `jaconv.h2z(kana=True, ascii=True, digit=True)` character map.",
        "const _h2zMap = <int, String>{",
        *[f"  0x{k:x}: {dart_str(v)}," for k, v in table.items()],
        "};",
        "",
        "/// Mojibake ellipsis replaced by `...` in the original.",
        f"const _mojibakeEllipsis = {dart_str(mojibake)};",
        "",
        "/// Characters of the original's `[...]{2,}` dot-run class (besides `.`).",
        f"const _mojibakeDotClass = {dart_str(mojibake_class)};",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(REPO), len(pairs), "dakuten,", len(table), "chars")


if __name__ == "__main__":
    main()
