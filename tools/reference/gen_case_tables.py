"""Generates packages/ct_core/lib/src/translation/py_case_tables.g.dart: the
Unicode case mappings where Python's str.upper()/lower()/capitalize() differ
from a one-to-one character mapping (SpecialCasing expansions, title case).

    uv run python -B gen_case_tables.py
"""

from __future__ import annotations

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUT = REPO / "packages" / "ct_core" / "lib" / "src" / "translation" / "py_case_tables.g.dart"
BS = chr(92)


def dart_str(s: str) -> str:
    return "'" + "".join(BS + f"u{{{ord(c):x}}}" for c in s) + "'"


def main() -> None:
    upper, lower, title = {}, {}, {}
    for cp in range(sys.maxunicode + 1):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        c = chr(cp)
        if len(c.upper()) > 1:
            upper[cp] = c.upper()
        if len(c.lower()) > 1:
            lower[cp] = c.lower()
        if c.title() != c.upper() or len(c.title()) > 1:
            title[cp] = c.title()

    def table(name: str, doc: str, m: dict[int, str]) -> list[str]:
        return [f"/// {doc}", f"const {name} = <int, String>{{", *[f"  0x{k:x}: {dart_str(v)}," for k, v in m.items()], "};", ""]

    lines = [
        "// GENERATED by tools/reference/gen_case_tables.py — do not edit.",
        f"// Python {sys.version.split()[0]}, Unicode {__import__('unicodedata').unidata_version}.",
        "",
        "part of 'llm_protocol.dart';",
        "",
        *table("_pyUpperSpecial", "Characters whose `str.upper()` has several characters.", upper),
        *table("_pyLowerSpecial", "Characters whose `str.lower()` has several characters.", lower),
        *table("_pyTitleSpecial", "Characters whose title case differs from their upper case.", title),
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote", OUT.relative_to(REPO), len(upper), len(lower), len(title))


if __name__ == "__main__":
    main()
